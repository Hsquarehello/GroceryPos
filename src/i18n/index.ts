export function t(
  key: TranslationKey,
  values?: Record<string, string | number>,
): string {
  let value = my[key];
  if (!values) return value;
  return Object.entries(values).reduce<string>(
    (result, [name, replacement]) =>
      result.replace(`{${name}}`, String(replacement)),
    value as string,
  );
}

